#!/usr/bin/env node
// Summarise bench/results/*/result.json into bench/RESULTS.md (one row per run, then averages per arm).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(ROOT, 'results');
const runs = fs.existsSync(dir) ? fs.readdirSync(dir).map((d) => path.join(dir, d, 'result.json')).filter((f) => fs.existsSync(f)).map((f) => JSON.parse(fs.readFileSync(f, 'utf8'))) : [];
runs.sort((a, b) => a.scenario.localeCompare(b.scenario) || a.arm.localeCompare(b.arm) || a.date.localeCompare(b.date));
const k = (n) => (n >= 1e6 ? `${(n / 1e6).toFixed(2)}M` : n >= 1e3 ? `${Math.round(n / 1e3)}k` : String(n));
const pct = (r) => (r.hidden.total ? `${r.hidden.pass}/${r.hidden.total} (${Math.round((r.hidden.pass / r.hidden.total) * 100)}%)` : 'no tests ran');
// Older results predate the status and kit fields.
const checks = (r) => { const ran = (r.quality || []).filter((q) => q.pass !== null); return ran.length ? `${ran.filter((q) => q.pass).length}/${ran.length}` : '—'; };
const rows = runs.map((r) => `| ${r.scenario} | ${r.arm} | ${r.model} | ${pct(r)} | ${checks(r)} | ${r.status || '—'} | $${r.costUsd.toFixed(2)} | ${r.minutes} | ${r.messages} (${r.scriptedReplies} scripted) | ${k(r.tokens.total)} | ${k(r.tokens.output)} | ${r.kitDigest || '—'} | ${r.date.slice(0, 10)} |`);
const groups = new Map();
for (const r of runs) { const key = `${r.scenario}|${r.arm}|${r.kitDigest || '—'}`; (groups.get(key) || groups.set(key, []).get(key)).push(r); }
const avg = (list, f) => list.reduce((a, r) => a + f(r), 0) / list.length;
// Mean, with the min–max range once there is more than one run.
const spread = (list, f, fmt) => { const v = list.map(f); return `${fmt(avg(list, f))}${list.length > 1 ? ` (${fmt(Math.min(...v))}–${fmt(Math.max(...v))})` : ''}`; };
const rate = (r) => (r.hidden.total ? r.hidden.pass / r.hidden.total : 0);
const summary = [...groups.entries()].map(([key, list]) => {
  const [scenario, arm, kit] = key.split('|');
  const passRate = avg(list, rate);
  const cost = avg(list, (r) => r.costUsd);
  const completed = list.filter((r) => !r.status || r.status === 'completed').length;
  return `| ${scenario} | ${arm} | ${kit} | ${list.length} | ${completed}/${list.length} | ${spread(list, rate, (x) => `${Math.round(x * 100)}%`)} | ${spread(list, (r) => r.costUsd, (x) => `$${x.toFixed(2)}`)} | ${spread(list, (r) => r.minutes, (x) => x.toFixed(1))} | ${k(Math.round(avg(list, (r) => r.tokens.total)))} | ${passRate ? `$${(cost / (passRate * list[0].hidden.total)).toFixed(3)}` : '—'} |`;
});
// Per test group (prompt-stated vs owner-only facts, each change request, existing behaviour), averaged per scenario/arm/kit.
const groupRows = [...groups.entries()].flatMap(([key, list]) => {
  const [scenario, arm, kit] = key.split('|');
  const names = [...new Set(list.flatMap((r) => Object.keys(r.hidden.groups || {})))];
  if (names.length < 2) return [];
  return [`| ${scenario} | ${arm} | ${kit} | ${names.map((g) => { const v = list.map((r) => r.hidden.groups?.[g]).filter(Boolean); return `${g} ${v.reduce((a, x) => a + x.pass, 0)}/${v.reduce((a, x) => a + x.total, 0)}`; }).join(' · ')} |`];
});
const modelRows = runs.filter((r) => r.costByModel && Object.keys(r.costByModel).length).map((r) => `| ${r.scenario} | ${r.arm} | ${r.date.slice(0, 16)} | ${Object.entries(r.costByModel).sort((a, b) => b[1] - a[1]).map(([m, v]) => `${m.replace(/^claude-/, '')} $${v.toFixed(2)} (${r.costUsd ? Math.round((v / r.costUsd) * 100) : 0}%)`).join(' · ')} |`);
const reviewed = runs.filter((r) => r.review?.scores);
const reviewRows = reviewed.map((r) => `| ${r.scenario} | ${r.arm} | ${['correctness', 'maintainability', 'tests', 'documentation', 'security'].map((k) => r.review.scores[k] ?? '—').join(' | ')} | ${String(r.review.scores.notes || '').replace(/\|/g, '/').slice(0, 160)} |`);
const qualityRows = runs.filter((r) => r.quality?.length).map((r) => `| ${r.scenario} | ${r.arm} | ${r.date.slice(0, 16)} | ${r.quality.map((q) => `${q.name}: ${q.pass === null ? 'not run' : q.pass ? 'pass' : `fail${q.errors ? ` (${q.errors})` : ''}`}`).join(' · ')} |`);
const md = `# Benchmark results

Generated by \`node bench/report.js\` from \`bench/results/*/result.json\`. See [bench/README.md](README.md) for the method.

## Averages per scenario and arm

Values are means; with several runs the min–max range follows in brackets. "Finished" counts runs that ended
on their own rather than at the message, budget or host-error limit (older results without a status count as finished).
Runs are grouped by kit digest (a hash of kit/ and src/ at run time), so results before and after a kit change stay separate.

| Scenario | Arm | Kit | Runs | Finished | Hidden tests passed | Cost | Minutes | Tokens | Cost per passing test |
|---|---|---|---|---|---|---|---|---|---|
${summary.join('\n')}

${groupRows.length ? `## Hidden tests by group

Groups come from test-name prefixes: \`prompt\` is behaviour stated in the request, owner-fact groups are answerable only by asking the product owner, \`change N\` is each mid-build change, \`existing\` is behaviour of the seeded product that must not regress.

| Scenario | Arm | Kit | Passed per group (all runs) |
|---|---|---|---|
${groupRows.join('\n')}
` : ''}
${qualityRows.length ? `## Quality checks per run

Run after the build and never shown to the agent: committed secrets, the agent's own test suite, semgrep (when installed) and scenario platform checks (\`quality.json\`).

| Scenario | Arm | Run | Checks |
|---|---|---|---|
${qualityRows.join('\n')}
` : ''}
${modelRows.length ? `## Cost by model per run

From Claude Code's per-model usage (main session and sub-agents). The tiered arm should move work from the session model to cheaper models.

| Scenario | Arm | Run | Cost by model |
|---|---|---|---|
${modelRows.join('\n')}
` : ''}
${reviewRows.length ? `## Blind review (1–5, \`--review\`)

| Scenario | Arm | Correctness | Maintainability | Tests | Documentation | Security | Notes |
|---|---|---|---|---|---|---|---|
${reviewRows.join('\n')}
` : ''}
## Every run

| Scenario | Arm | Model | Hidden tests | Quality checks | Status | Cost | Minutes | Messages | Tokens | Output tokens | Kit | Date |
|---|---|---|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}
`;
fs.writeFileSync(path.join(ROOT, 'RESULTS.md'), md);
console.log(md);
