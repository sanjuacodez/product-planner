#!/usr/bin/env node
// Summarise bench/results/*/result.json into bench/RESULTS.md (one row per run, then averages per arm).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(ROOT, 'results');
const runs = fs.existsSync(dir) ? fs.readdirSync(dir).map((d) => path.join(dir, d, 'result.json')).filter((f) => fs.existsSync(f)).map((f) => JSON.parse(fs.readFileSync(f, 'utf8'))) : [];
runs.sort((a, b) => a.scenario.localeCompare(b.scenario) || a.arm.localeCompare(b.arm) || a.date.localeCompare(b.date));
const k = (n) => (n >= 1e6 ? `${(n / 1e6).toFixed(2)}M` : n >= 1e3 ? `${Math.round(n / 1e3)}k` : String(n));
const pct = (r) => (r.hidden.total ? `${r.hidden.pass}/${r.hidden.total} (${Math.round((r.hidden.pass / r.hidden.total) * 100)}%)` : 'no tests ran');
const rows = runs.map((r) => `| ${r.scenario} | ${r.arm} | ${r.model} | ${pct(r)} | $${r.costUsd.toFixed(2)} | ${r.minutes} | ${r.messages} (${r.scriptedReplies} scripted) | ${k(r.tokens.total)} | ${k(r.tokens.output)} | ${r.date.slice(0, 10)} |`);
const groups = new Map();
for (const r of runs) { const key = `${r.scenario}|${r.arm}`; (groups.get(key) || groups.set(key, []).get(key)).push(r); }
const avg = (list, f) => list.reduce((a, r) => a + f(r), 0) / list.length;
const summary = [...groups.entries()].map(([key, list]) => {
  const [scenario, arm] = key.split('|');
  const passRate = avg(list, (r) => (r.hidden.total ? r.hidden.pass / r.hidden.total : 0));
  const cost = avg(list, (r) => r.costUsd);
  return `| ${scenario} | ${arm} | ${list.length} | ${Math.round(passRate * 100)}% | $${cost.toFixed(2)} | ${avg(list, (r) => r.minutes).toFixed(1)} | ${k(Math.round(avg(list, (r) => r.tokens.total)))} | ${passRate ? `$${(cost / (passRate * list[0].hidden.total)).toFixed(3)}` : '—'} |`;
});
const md = `# Benchmark results

Generated by \`node bench/report.js\` from \`bench/results/*/result.json\`. See [bench/README.md](README.md) for the method.

## Averages per scenario and arm

| Scenario | Arm | Runs | Hidden tests passed | Cost | Minutes | Tokens | Cost per passing test |
|---|---|---|---|---|---|---|---|
${summary.join('\n')}

## Every run

| Scenario | Arm | Model | Hidden tests | Cost | Minutes | Messages | Tokens | Output tokens | Date |
|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}
`;
fs.writeFileSync(path.join(ROOT, 'RESULTS.md'), md);
console.log(md);
